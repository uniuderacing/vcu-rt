/// Representation of the current VCU power consumption.
#[derive(Clone)]
pub struct PowerConsumption {
    /// Shared reference to the current measured voltage from the eFuse.
    v_ilm: Arc<AtomicF32>,
    /// Values of the two constants `G_imon` and `R_ilm` for the eFuse.
    efuse_constants: (f64, f64),
}

impl PowerConsumption {
    /// Constructs a new instance of [`PowerConsumption`].
    pub(crate) const fn new(v_ilm: Arc<AtomicF32>, efuse_constants: (f64, f64)) -> Self {
        Self {
            v_ilm,
            efuse_constants,
        }
    }

    /// Returns the VCU power consumption measured in Ampere.
    #[must_use]
    pub fn amps(&self) -> f64 {
        self.milliamps() * 1e-3
    }

    /// Returns the VCU power consumption measured in milli-Ampere.
    #[must_use]
    pub fn milliamps(&self) -> f64 {
        let (g_imon, r_ilm) = self.efuse_constants;
        let v_ilm = self.v_ilm.load(Ordering::SeqCst); // In mV
        f64::from(v_ilm) / (g_imon * r_ilm)
    }
}

