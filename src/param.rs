/// Priority-aware asynchronous task executor.
#[derive(Clone, Debug)]
pub struct Executor {
    /// Multi-threaded async executor for standard tasks.
    standard: futures::executor::ThreadPool,
    /// Multi-threaded async executor for critical tasks.
    critical: futures::executor::ThreadPool,
}

impl Executor {
    /// Constructs a new instance of [`Executor`].
    pub(crate) fn new(use_critical: bool) -> Result<Self, ExecutorError> {
        let num_cores = esp_idf_hal::cpu::CORES;
        let (standard, critical) = if use_critical && num_cores > 1 {
            match num_cores {
                2 => {
                    // Standard executor pinned to CPU core 0
                    esp_idf_hal::task::thread::ThreadSpawnConfiguration {
                        pin_to_core: Some(esp_idf_hal::cpu::Core::from(0)),
                        ..Default::default()
                    }
                    .set()
                    .map_err(ExecutorError::Platform)?;
                    let standard = futures::executor::ThreadPool::builder()
                        .name_prefix("vcu_rt_worker_")
                        .stack_size(12 * 1024)
                        .pool_size(1)
                        .create()
                        .map_err(ExecutorError::ThreadPool)?;

                    // Critical executor pinned to CPU core 1
                    esp_idf_hal::task::thread::ThreadSpawnConfiguration {
                        pin_to_core: Some(esp_idf_hal::cpu::Core::from(1)),
                        ..Default::default()
                    }
                    .set()
                    .map_err(ExecutorError::Platform)?;
                    let critical = futures::executor::ThreadPool::builder()
                        .name_prefix("vcu_rt_critical_worker_")
                        .stack_size(12 * 1024)
                        .pool_size(1)
                        .create()
                        .map_err(ExecutorError::ThreadPool)?;

                    esp_idf_hal::task::thread::ThreadSpawnConfiguration::default()
                        .set()
                        .map_err(ExecutorError::Platform)?;
                    (standard, critical)
                }
                _ => {
                    // Currently, no ESP has more than 2 physical cores
                    // This may change in the future though
                    unreachable!();
                }
            }
        } else {
            if use_critical {
                // If there aren't critical tasks, this log message is never printed
                // On the other hand, if there are critical task but >1 cores, the `if` branch above is taken
                // So this log mesagge is correctly printed if and only if there is a single core and there is at least
                // one critical task
                log::warn!("This VCU has a single CPU core, so tasks marked as critical cannot be prioritized");
            }
            let standard = futures::executor::ThreadPool::builder()
                .name_prefix("vcu_rt_worker_")
                .stack_size(12 * 1024)
                .pool_size(num_cores as usize)
                .create()
                .map_err(ExecutorError::ThreadPool)?;
            (standard.clone(), standard)
        };
        Ok(Self { standard, critical })
    }

    /// Spawns a (possibly critical) future onto this executor, returning a task handle.
    ///
    /// # Errors
    ///
    /// This function returns an error if it fails to spawn the provided future onto the runtime's internal executor.
    pub fn spawn<F>(
        &self,
        future: F,
        critical: bool,
    ) -> Result<futures::future::RemoteHandle<<F as Future>::Output>, futures::task::SpawnError>
    where
        F: Future + Send + 'static,
        <F as Future>::Output: Send,
    {
        if critical {
            self.critical.spawn_with_handle(future)
        } else {
            self.standard.spawn_with_handle(future)
        }
    }
}

/// Errors generated by an [`Executor`].
#[derive(Debug, thiserror::Error)]
pub enum ExecutorError {
    /// Failure during the interaction with CPU cores.
    #[error("CPU cores interaction failure")]
    Platform(esp_idf_sys::EspError),
    /// Failure during the construction of the async executor worker thread pool.
    #[error("async executor worker thread pool build failure")]
    ThreadPool(std::io::Error),
}

