/// Representation of the current CAN bus load.
#[derive(Clone)]
pub struct CanBusLoad {
    /// Shared reference to the current CAN bus load.
    bit_load: Arc<AtomicUsize>,
}

impl CanBusLoad {
    /// Constructs a new instance of [`CanBusLoad`].
    pub(crate) const fn new(bit_load: Arc<AtomicUsize>) -> Self {
        Self { bit_load }
    }

    /// Returns the CAN bus load percentage, given its bandwidth capacity.
    /// The result is expressed as a percentage, between 0 and 100.
    /// Note: due to the involved calculations, the returned result is just an estimate, so the resulting value may
    /// slightly exceed 100% due to estimation error.
    #[must_use]
    pub fn percentage(&self, bandwidth: can::config::Timing) -> f32 {
        let bit_load = self.bit_load.load(Ordering::SeqCst);
        let capacity =
            Self::max_bits_per_second(bandwidth) * config::can::LOAD_ESTIMATION_WINDOW.as_secs();
        #[allow(clippy::cast_precision_loss)]
        let load_percentage = (bit_load as f32) * 100.0 / (capacity as f32);
        load_percentage
    }

    /// Returns the theoretical maximum number of bits that can be sent on a CAN bus operating at the given bandwidth.
    fn max_bits_per_second(bandwidth: can::config::Timing) -> u64 {
        match bandwidth {
            can::config::Timing::B25K => 25_000,
            can::config::Timing::B50K => 50_000,
            can::config::Timing::B100K => 100_000,
            can::config::Timing::B125K => 125_000,
            can::config::Timing::B250K => 250_000,
            can::config::Timing::B500K => 500_000,
            can::config::Timing::B800K => 800_000,
            can::config::Timing::B1M => 1_000_000,
            can::config::Timing::Custom {
                baudrate_prescaler,
                timing_segment_1,
                timing_segment_2,
                ..
            } => {
                // Reference: <https://docs.espressif.com/projects/esp-idf/en/v3.3/api-reference/peripherals/can.html#bit-timing>
                (80_000_000
                    / (baudrate_prescaler * u32::from(1 + timing_segment_1 + timing_segment_2)))
                .into()
            }
        }
    }
}

// +--------+
// | KindId |
// +--------+

/// A [`KindId`] is similar to a [`TypeId`], but coarser (i.e. different types can have the same kind).
/// This is mainly used to aggregate messages into classes that can span multiple different types. For example, all
/// inverter control messages (which are different types) have the same kind.
/// This is mainly used inside a [`CanStream`] in order to avoid queuing old, irrelevant instances of a message of the
/// same kind of a newer one, in order to minimize latency.
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
enum KindId {
    /// Inverter control messages.
    InverterControl,
    /// Types that do not have a special kind fallback to their [`TypeId`].
    Other(TypeId),
}

impl KindId {
    /// Returns the [`KindId`] of the provided message type.
    fn of<M>() -> Self
    where
        M: GeneralMessageTrait + Into<Message> + Send + 'static,
    {
        let type_id = TypeId::of::<M>();
        if type_id == TypeId::of::<serena_messages::SetInverterSpeedMessage>()
            || type_id == TypeId::of::<serena_messages::SetInverterAcCurrentMessage>()
            || type_id == TypeId::of::<serena_messages::SetInverterBrakeCurrentMessage>()
            || type_id == TypeId::of::<serena_messages::SetInverterRelativeCurrentMessage>()
            || type_id == TypeId::of::<serena_messages::SetInverterRelativeBrakeCurrentMessage>()
        {
            Self::InverterControl
        } else {
            Self::Other(type_id)
        }
    }
}

