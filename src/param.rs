/// An element of the internal queues of a [`CanStream`].
#[derive(Clone, Copy, Debug)]
enum QueueElement {
    /// Regular queued message.
    Standard(Message),
    /// Overridable queued message, which needs to be recovered from the hash map.
    Overridable(KindId),
}

/// Smart queue for messages to be sent on the CAN bus by tasks.
///
/// This queue implements the following "smart" features:
/// - some message types, which we call _overridable_, lose their relevance after a new message of the same type is
///   produced (e.g. inverter control messages). If a message of such type is produced faster than it can be sent on the
///   CAN bus, using a traditional queue would waste resources on old message instances which are no longer relevant,
///   thus introducing delays. [`CanStream`] solves the problem by applying some additional logic to treat those
///   specific message types;
/// - message types are classified in two priority tiers (low/high), with separate and dedicated queues.
#[derive(Clone)]
pub struct CanStream {
    /// Queue for high-priority messages.
    high_priority_queue: (flume::Sender<QueueElement>, flume::Receiver<QueueElement>),
    /// Queue for low-priority messages.
    low_priority_queue: (flume::Sender<QueueElement>, flume::Receiver<QueueElement>),
    /// Collection of all the queued instances of messages that are _overridable_.
    overridables: Arc<SyncMutex<HashMap<KindId, Message>>>,
}

impl CanStream {
    /// Constructs a new instance of [`CanStream`].
    /// The caller can optionally provide custom queue lengths with the dedicated parameter for both high- and
    /// low-priority messages, respectively.
    pub(crate) fn new(queue_lengths: Option<(usize, usize)>) -> Self {
        let (high_priority_queue_len, low_priority_queue_len) = queue_lengths.unwrap_or((48, 64));
        Self {
            high_priority_queue: flume::bounded(high_priority_queue_len),
            low_priority_queue: flume::bounded(low_priority_queue_len),
            overridables: Arc::new(SyncMutex::new(HashMap::new())),
        }
    }

    /// Sends the provided message on the CAN bus.
    #[allow(clippy::missing_panics_doc)]
    pub fn send<M>(&self, item: M)
    where
        M: GeneralMessageTrait + Into<Message> + Send + 'static,
    {
        if let Some(queue_element) = self.build_queue_element(item) {
            if Self::is_high_priority::<M>() {
                self.high_priority_queue.0.send(queue_element)
            } else {
                self.low_priority_queue.0.send(queue_element)
            }
            .unwrap(); // Receiver is stored in `self`
        }
    }

    /// Sends the provided message on the CAN bus.
    #[allow(clippy::missing_panics_doc)]
    pub async fn send_async<M>(&self, item: M)
    where
        M: GeneralMessageTrait + Into<Message> + Send + 'static,
    {
        if let Some(queue_element) = self.build_queue_element(item) {
            if Self::is_high_priority::<M>() {
                self.high_priority_queue.0.send_async(queue_element).await
            } else {
                self.low_priority_queue.0.send_async(queue_element).await
            }
            .unwrap(); // Receiver is stored in `self`
        }
    }

    /// Processes an item and builds the corresponding [`QueueElement`].
    /// If an _overridable_ message of the same type is already in the queue, this function updates its contents in the
    /// internal hash map and returns `None`.
    fn build_queue_element<M>(&self, item: M) -> Option<QueueElement>
    where
        M: GeneralMessageTrait + Into<Message> + Send + 'static,
    {
        let message: Message = item.into();
        if Self::is_overridable::<M>() {
            let kind_id = KindId::of::<M>();
            if self
                .overridables
                .lock()
                .unwrap()
                .insert(kind_id, message)
                .is_some()
            {
                log::warn!(
                    "Overridable message of type {} (kind {kind_id:?}) is being produced faster than it can be sent on the CAN bus",
                    std::any::type_name::<M>(),
                );
                None
            } else {
                Some(QueueElement::Overridable(kind_id))
            }
        } else {
            Some(QueueElement::Standard(message))
        }
    }

    /// Tries to receive a message from the internal CAN bus queue.
    pub(crate) fn try_recv(&self) -> Option<Message> {
        // Check high-priority queue
        match self.high_priority_queue.1.try_recv() {
            Ok(queue_element) => return Some(self.unwrap_queue_element(queue_element)),
            Err(flume::TryRecvError::Empty) => (),
            Err(_) => {
                // Channel sender is stored in `self`, so it can never be dropped
                unreachable!()
            }
        }

        // Check low-priority queue
        match self.low_priority_queue.1.try_recv() {
            Ok(queue_element) => return Some(self.unwrap_queue_element(queue_element)),
            Err(flume::TryRecvError::Empty) => (),
            Err(_) => {
                // Channel sender is stored in `self`, so it can never be dropped
                unreachable!()
            }
        }

        None
    }

    /// Retrieves a `Message` from the provided [`QueueElement`].
    fn unwrap_queue_element(&self, queue_element: QueueElement) -> Message {
        match queue_element {
            QueueElement::Standard(message) => message,
            QueueElement::Overridable(kind_id) => {
                self.overridables.lock().unwrap().remove(&kind_id).unwrap()
            }
        }
    }

    /// Returns true if and only if the given message type is high-priority.
    fn is_high_priority<M>() -> bool
    where
        M: GeneralMessageTrait + Into<Message> + Send + 'static,
    {
        let msg_type = TypeId::of::<M>();
        msg_type == TypeId::of::<serena_messages::SetInverterSpeedMessage>()
            || msg_type == TypeId::of::<serena_messages::SetInverterAcCurrentMessage>()
            || msg_type == TypeId::of::<serena_messages::SetInverterBrakeCurrentMessage>()
            || msg_type == TypeId::of::<serena_messages::SetInverterRelativeCurrentMessage>()
            || msg_type == TypeId::of::<serena_messages::SetInverterRelativeBrakeCurrentMessage>()
            || msg_type == TypeId::of::<serena_messages::SetInverterMaximumAcCurrentMessage>()
            || msg_type == TypeId::of::<serena_messages::SetInverterMaximumDcCurrentMessage>()
            || msg_type == TypeId::of::<serena_messages::SetInverterMaximumAcBrakeCurrentMessage>()
            || msg_type == TypeId::of::<serena_messages::SetInverterMaximumDcBrakeCurrentMessage>()
            || msg_type == TypeId::of::<serena_messages::InverterDriveEnableMessage>()
            || msg_type == TypeId::of::<serena_messages::BrainStatusMessage>() // So that settring wheel updates ASAP
    }

    /// Returns true if and only if the given message type is _overridable_, i.e. if old instances of the same message
    /// type are no longer relevant after a newer one has been produced.
    fn is_overridable<M>() -> bool
    where
        M: GeneralMessageTrait + Into<Message> + Send + 'static,
    {
        let msg_type = TypeId::of::<M>();
        msg_type == TypeId::of::<serena_messages::SetInverterSpeedMessage>()
            || msg_type == TypeId::of::<serena_messages::SetInverterAcCurrentMessage>()
            || msg_type == TypeId::of::<serena_messages::SetInverterBrakeCurrentMessage>()
            || msg_type == TypeId::of::<serena_messages::SetInverterRelativeCurrentMessage>()
            || msg_type == TypeId::of::<serena_messages::SetInverterRelativeBrakeCurrentMessage>()
            || msg_type == TypeId::of::<serena_messages::SetInverterMaximumAcCurrentMessage>()
            || msg_type == TypeId::of::<serena_messages::SetInverterMaximumDcCurrentMessage>()
            || msg_type == TypeId::of::<serena_messages::SetInverterMaximumAcBrakeCurrentMessage>()
            || msg_type == TypeId::of::<serena_messages::SetInverterMaximumDcBrakeCurrentMessage>()
            || msg_type == TypeId::of::<serena_messages::InverterDriveEnableMessage>()
    }
}

